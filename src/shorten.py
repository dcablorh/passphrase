"""Shorten a generated NEAR recovery phrase to 6 words, plus a user secret.

Scheme (v1, 6 words = 66 bits):
  E = 128-bit BIP-39 entropy = A (66 bits) || B (62 bits)
  A is random, chosen at generation time.
  B = first 62 bits of scrypt(secret, salt_B)   <- derived from the secret
  Q = A XOR first 66 bits of scrypt(secret, salt_A)  -> 6 words (11 bits each)

Stored: the 6 words Q only.
Restore: A = Q XOR KDF_A(secret), B = KDF_B(secret), E = A||B, phrase = mnemonic(E).

Limits: only works for phrases generated by this scheme (B must come from the
secret). Security against offline guessing of the secret is about 62 bits,
and scrypt cost is the main defence. See docs/02-technical-design.md.
"""
import hashlib
import os

from mnemonic import Mnemonic

from src.derive import key_from_phrase

WORDLIST = Mnemonic("english").wordlist          # 2048 words, index = 11-bit value
SHORT_WORDS = 6
A_BITS = 66
B_BITS = 62
SCRYPT = dict(n=2**15, r=8, p=1, dklen=16)       # 16 bytes = 128 bits of KDF output
MIN_SECRET_LEN = 20                              # characters; see note in MIN_SECRET_NOTE
MIN_SECRET_NOTE = "Use at least 20 characters or 6+ random words."


def _kdf_bits(secret: str, label: bytes, bits: int) -> int:
    raw = hashlib.scrypt(secret.encode(), salt=label, maxmem=64 * 1024 * 1024, **SCRYPT)
    return int.from_bytes(raw, "big") >> (128 - bits)


def _check_secret(secret: str) -> None:
    if len(secret) < MIN_SECRET_LEN:
        raise ValueError(MIN_SECRET_NOTE)


def _to_words(value: int) -> list[str]:
    return [WORDLIST[(value >> (11 * (SHORT_WORDS - 1 - i))) & 0x7FF] for i in range(SHORT_WORDS)]


def _from_words(words: list[str]) -> int:
    if len(words) != SHORT_WORDS:
        raise ValueError(f"expected {SHORT_WORDS} words")
    value = 0
    for w in words:
        try:
            idx = WORDLIST.index(w.strip().lower())
        except ValueError as exc:
            raise ValueError(f"not a BIP-39 word: {w!r}") from exc
        value = (value << 11) | idx
    return value


def new_short_wallet(secret: str) -> dict:
    """Generate a fresh wallet from a secret. Returns the 6-word short form and the full key data."""
    _check_secret(secret)
    a = int.from_bytes(os.urandom(9), "big") >> 6            # 66 random bits
    b = _kdf_bits(secret, b"rps-v1-B", B_BITS)               # 62 bits from the secret
    entropy = ((a << B_BITS) | b).to_bytes(16, "big")
    phrase = Mnemonic("english").to_mnemonic(entropy)
    q = a ^ _kdf_bits(secret, b"rps-v1-A", A_BITS)           # mask A with the secret
    key = key_from_phrase(phrase)
    return {"short_words": _to_words(q), "seed_phrase": phrase,
            "account_id": key["public_key_hex"], "public_key": key["public_key"]}


def restore_phrase(short_words: list[str], secret: str) -> str:
    """Rebuild the 12-word phrase from the 6-word short form and the secret."""
    _check_secret(secret)
    q = _from_words(short_words)
    a = q ^ _kdf_bits(secret, b"rps-v1-A", A_BITS)
    b = _kdf_bits(secret, b"rps-v1-B", B_BITS)
    entropy = ((a << B_BITS) | b).to_bytes(16, "big")
    return Mnemonic("english").to_mnemonic(entropy)
